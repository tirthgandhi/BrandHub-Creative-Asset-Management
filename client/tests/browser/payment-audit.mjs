import { chromium } from "playwright-core";
import fs from "node:fs/promises";
import assert from "node:assert/strict";
const origin = process.env.BRANDHUB_TEST_URL || "http://127.0.0.1:5178";
const browser = await chromium.launch({ executablePath: process.env.BRANDHUB_BROWSER || "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe", headless: true });
const result = { checks: [] };
async function login(label) {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  await page.goto(`${origin}/login`, { waitUntil: "domcontentloaded" });
  await page.getByRole("button", { name: label, exact: true }).click();
  await page.locator("#login-email").fill(({ "Project Manager": "admin@brandhub.example", "Designer": "nisha.verma@brandhub.example", "Super Admin": "superadmin@brandhub.example", "Client": "iris.vale@brandhub.example" })[label]);
  await page.locator("#login-password").fill("Brand123");
  await page.getByRole("button", { name: `Sign in as ${label}`, exact: true }).click();
  await page.waitForURL("**/app/dashboard", { waitUntil: "domcontentloaded" });
  return { context, page };
}
try {
  const c = await login("Client");
  await c.page.goto(`${origin}/app/requests/new`, { waitUntil: "domcontentloaded" });
  const title = `Contact and payment prototype ${Date.now()}`;
  await c.page.getByLabel(/^Project title/).fill(title);
  await c.page.getByLabel(/^Description/).fill("Create a skincare campaign with contact details, a proposed amount, and a demo payment receipt.");
  await c.page.getByLabel(/^Phone number/).fill("+91 90000 00000");
  await c.page.getByLabel(/^Company/).fill("GlowTheory prototype");
  await c.page.getByLabel(/^Project amount/).fill("12500.50");
  const creation = c.page.waitForResponse(r => r.url().endsWith("/api/project-requests") && r.request().method() === "POST");
  await c.page.getByRole("button", { name: "Submit request", exact: true }).click();
  const created = await creation; assert.equal(created.status(), 201);
  const brief = (await created.json()).data.projectRequest;
  result.requestId = brief.id;
  assert.equal(brief.amount, 12500.5); assert.equal(brief.contactDetails.phone, "+91 90000 00000");
  result.checks.push("Client UI submits contact details and INR amount to the database");
  const m = await login("Project Manager");
  await m.page.goto(`${origin}/app/management/requests`, { waitUntil: "domcontentloaded" });
  let managerCard = m.page.locator("article.workspace-request").filter({ has: m.page.getByRole("heading", { name: title, exact: true }) });
  await managerCard.getByText("+91 90000 00000", { exact: true }).waitFor();
  await managerCard.getByText("₹12,500.50", { exact: true }).waitFor();
  result.checks.push("Manager sees the client's contact details and proposed amount");
  await managerCard.getByRole("button", { name: "Approve", exact: true }).click();
  await m.page.getByRole("checkbox", { name: "Nisha Verma", exact: true }).check();
  const approval = m.page.waitForResponse(r => r.url().endsWith(`/api/project-requests/${brief.id}`) && r.request().method() === "PATCH");
  await m.page.getByRole("button", { name: "Approve and create project", exact: true }).click();
  assert.equal((await approval).status(), 200);
  result.checks.push("Manager approves the amount and assigns the designer");
  await c.page.goto(`${origin}/app/requests`, { waitUntil: "domcontentloaded" });
  let clientCard = c.page.locator("article.workspace-request").filter({ has: c.page.getByRole("heading", { name: title, exact: true }) });
  await clientCard.getByRole("button", { name: "Make demo payment", exact: true }).click();
  const declined = c.page.waitForResponse(r => r.url().endsWith(`/api/project-requests/${brief.id}/payment`));
  await c.page.getByRole("button", { name: "Simulate declined payment", exact: true }).click();
  assert.equal((await declined).status(), 402);
  await c.page.getByRole("alert").getByText(/Demo payment was declined/).waitFor();
  result.checks.push("Declined demo payment shows an error and does not mark the request paid");
  const payment = c.page.waitForResponse(r => r.url().endsWith(`/api/project-requests/${brief.id}/payment`));
  await c.page.getByRole("button", { name: /^Pay .*demo$/ }).click();
  const paid = await payment; assert.equal(paid.status(), 200);
  const receipt = (await paid.json()).data.projectRequest.payment;
  assert.equal(receipt.status, "paid"); assert.equal(receipt.isDemo, true); result.reference = receipt.reference;
  await clientCard.getByText(`Demo receipt · ${receipt.reference}`, { exact: true }).waitFor();
  await clientCard.screenshot({ path: "docs/testing/prototype/role-audit/client-payment.png" });
  await c.page.reload({ waitUntil: "domcontentloaded" });
  await c.page.getByText(`Demo receipt · ${receipt.reference}`, { exact: true }).waitFor();
  result.checks.push("Successful demo receipt persists after page reload");
  await m.page.reload({ waitUntil: "domcontentloaded" });
  managerCard = m.page.locator("article.workspace-request").filter({ has: m.page.getByRole("heading", { name: title, exact: true }) });
  await managerCard.getByText(`Demo receipt · ${receipt.reference}`, { exact: true }).waitFor();
  await managerCard.screenshot({ path: "docs/testing/prototype/role-audit/manager-payment.png" });
  result.checks.push("Manager sees the saved payment status and receipt");
  await c.page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await c.page.evaluate(() => globalThis.document.documentElement.scrollWidth > globalThis.innerWidth), false);
  clientCard = c.page.locator("article.workspace-request").filter({ has: c.page.getByRole("heading", { name: title, exact: true }) });
  await clientCard.screenshot({ path: "docs/testing/prototype/role-audit/payment-mobile.png" });
  result.checks.push("Contact, amount and receipt fit the mobile viewport");
  result.passed = true;
  await c.context.close(); await m.context.close();
} catch (error) { result.passed = false; result.failure = error.message; process.exitCode = 1; }
finally { await fs.writeFile("docs/testing/prototype/role-audit/payment-results.json", JSON.stringify(result, null, 2)); console.log(JSON.stringify(result)); await browser.close(); }
